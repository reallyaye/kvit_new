def _load_generated_translations() -> dict[str, str]:
    catalog_path = Path(__file__).resolve().parent.parent / "data" / "kk_translations.json"
    try:
        payload = json.loads(catalog_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    if not isinstance(payload, dict):
        return {}
    return {
        str(source): str(target)
        for source, target in payload.items()
        if isinstance(source, str) and isinstance(target, str) and source and target
    }


# Editorial-page catalog first, reviewed interface wording last. The curated
# entries override machine-assisted drafts whenever the same source key exists.
KK_TRANSLATIONS = {**_load_generated_translations(), **KK_TRANSLATIONS}

_TEXT_NODE_RE = re.compile(r">([^<>]+)<", re.DOTALL)


def _translate_text_node(match: re.Match[str]) -> str:
    raw_text = match.group(1)
    normalized = " ".join(html.unescape(raw_text).split())
    target = KK_TRANSLATIONS.get(normalized)
    if target is None:
        return match.group(0)

    leading = raw_text[: len(raw_text) - len(raw_text.lstrip())]
    trailing = raw_text[len(raw_text.rstrip()) :]
    return f">{leading}{html.escape(target, quote=False)}{trailing}<"


def translate_html(value: str) -> str:
    """Translate common visible UI strings when the request is in Kazakh."""
    if get_locale() != "kk" or not value:
        return value
    # CMS editors often format one visible sentence over several source lines.
    # Match its whitespace-normalized text first, then retain the legacy global
    # replacements for attributes, compact fragments and dynamic UI strings.
    translated = _TEXT_NODE_RE.sub(_translate_text_node, value)
    for source, target in sorted(KK_TRANSLATIONS.items(), key=lambda item: len(item[0]), reverse=True):
        translated = translated.replace(source, target)
    return translated
