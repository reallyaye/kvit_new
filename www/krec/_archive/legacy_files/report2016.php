<h1>Отчет о деятельности ТОО «КРЭК» по предоставлению услуг по передаче и (или) распределению электрической энергии в 2016 году перед потребителями и иными заинтересованными лицами</h1>
<p align="center"><b>Отчет</b></p>
<p align="center"><b>о деятельности ТОО "КРЭК" по предоставлению услуг по передаче и (или) распределению электрической энергии в 2016 году перед потребителями и иными заинтересованными лицами</b></p>
<p></p>
<p align="center"><b>14.04.2017 г. 15.00 ч.</b><b>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; г. Караганда</b></p>
<p align="center"><b>Краткая характеристика предприятия</b></p>
<p></p>
<p>Основным видом деятельности ТОО "Карагандинская региональная энергетическая компания" является передача и распределение электрической энергии. Регулируемые услуги оказываются на территории 4-х административных районов Карагандинской области: Абайский, Каркаралинский, Нуринский и Осакаровский. Общая площадь территории обслуживания 98,3 тыс. км<sup>2</sup>, радиус обслуживания электрических сетей составляет 550 км.</p>
<p>Электрические сети и оборудование эксплуатируется с 60-х годов и характеризуются значительной разбросанностью энергообъектов на обслуживаемой территории. Протяженность сетей 6 612 км., количество подстанций - 1068 подстанций и КТП, в которых установлено 1 115 трансформаторов. На балансе предприятия имеется спецтехника и транспорт в количестве 99 единиц. Численность персонала на конец года составила 450 человек. К сетям ТОО "КРЭК" подключены порядка 45 154 абонентов, из них физические лица - 43 462, юридические лица - 1 692.</p>
<p></p>
<p align="center"><b>1. Об исполнении инвестиционной программы</b></p>
<p></p>
<p>В рамках утвержденной инвестиционной программы на 2016 год ТОО "КРЭК" были выполнены мероприятия направленные на поддержание в рабочем состоянии основных средств. Сумма утвержденной Инвестиционной программы на 2016 год - 71 928,99 тыс.тенге. В период 2016 года проведен:</p>
<ol>
<li>капитальный ремонт ВЛ 35 кВ "Киргизия-Первомайская" с выносом участка протяженность 3 км;</li>
<li>капитальный ремонт ВЛ 35 кВ "Молодежная-Тельмана" с отпайкой на подстанцию "Весна" протяженность 7,074 км;</li>
<li>замена кабельных линий фидер № 10,18 от ПС "Заречная" до действующих ВЛ-6кВ протяженность 0,7 км.</li>
</ol>
<p>Кроме того, установлено 313 точек учета АСКУЭ нижнего уровня в г.Каркаралинск.</p>
<p></p>
<p>Мероприятия Инвестиционной программы выполнены в 100% объеме на сумму - 71 928,99 тыс.тенге.</p>
<p></p>
<p align="center"><b>2.Основные финансово-экономические показатели деятельности ТОО "КРЭК" за 2016 год</b></p>
<p></p>
<p align="center"><b><i>Доходы - 1 361 553 293 тенге</i></b></p>
<p>За отчетный период 2016 года доход от оказания регулируемых услуг по передаче и распределению электрической энергии составил 1 321 727 696 тенге. При расчете с потребителями за оказанные услуги предприятие применяло в январе тариф 4,54 тенге/кВтч без НДС, с 1 февраля 2016 года был введен предельный тариф в размере 5,18 который был утвержден приказом Департамента Комитета РК по регулированию естественных монополий и защите конкуренции Министерства национальной экономики по Карагандинской области № 264-ОД от 25.12.2015 года.</p>
<p>Доходы от иной деятельности - 39 825 597 тенге.</p>
<p></p>
<p align="center"><b><i>Расходы - 1 372 470 231 тенге</i></b></p>
<p>Себестоимость реализованной продукции - 1 219 437 992 тенге.</p>
<p>Административные расходы - 147 760 337 тенге</p>
<p>Прочие расходы - 5 271 902 тенге.</p>
<p></p>
<p align="center"><b><i>Результат финансово-хозяйственной деятельности</i></b></p>
<p>Убыток до налогообложения составил - 12 882 718 тенге.</p>
<p></p>
<p align="center"><b><i>Краткосрочная дебиторская задолженность - 178 639 тыс. тенге</i></b></p>
<p>ТОО "Жезказган энергосбыт" - 72 915 тыс. тенге</p>
<p>ТОО "Coal Trade Company" - 22 350 тыс. тенге</p>
<p>РГП "Канал им.К.Сатпаева" - 21 157 тыс. тенге</p>
<p>Прочие - 62 217 тыс. тенге</p>
<p></p>
<p align="center"><b><i>Краткосрочная кредиторская задолженность - 251 855 тыс. тенге</i></b></p>
<p>ТОО "АлмаТрансКомпани" - 113 345 тыс. тенге</p>
<p>ТОО "Техэлектропром" - 23 265 тыс. тенге</p>
