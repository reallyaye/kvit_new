<p>Убыток обусловлен дефицитом денежных средств, связанным с отсудившем платежей  ТОО «Жезказган энергосбыт»</p>
<p></p>
<p align="center"><b>6. Об объемах предоставленных услуг </b></p>
<p></p>
<p>Объем фактически оказанных за 1 полугодие 2020 года составил регулируемых услуг составил 125 928,033 тыс. кВт*ч. Потребителями ТОО «КРЭК» являются промышленные предприятия области и энергоснабжающие организации, которые осуществляют энергоснабжение на розничном рынке. Крупными потребителями электрической энергии за отчетный период стали :ТОО «Жезказган энергосбыт», ТОО «Промснаб-Астана». Объем транспорта электроэнергии для промышленных предприятий составил 22%, для энергоснабжающих организаций 88%.</p>
<p></p>
<p align="center"><b>7. Работа с потребителями услуг </b></p>
<p></p>
<p>Так как в числе потребителей энергоснабжающие организации, предприятие по заявкам этих организаций проводит отключения потребителей от энергоснабжения за нарушения Правил пользования электрической энергией, а также подключения к энергоснабжению после поступления заявок на подключение. </p>
<p>ТОО «КРЭК» осуществляет иную деятельность по установке приборов учета по заявкам потребителей, которая является технологически связанной с регулируемыми услугами в сфере передачи и распределения электрической энергии, сдает в аренду нежилые производственные помещения, проводит реализацию дров, а также проводит техническое обслуживание и монтаж оборудования сторонних организаций.</p>
<p>Предприятие выдает технические условия на проектирование новых объектов энергоснабжения, реконструкцию существующих, подключение новых мощностей потребителей к сетям ТОО «КРЭК». В первом полугодии 2020 года было выдано технических условий в количестве 88 потребителям, в т.ч.: юридическим лицам – 65, физическим лицам -239.</p>
<p></p>
<p align="center"><b>8. О перспективах деятельности </b></p>
<p></p>
<p>В качестве перспектив деятельности ТОО «КРЭК» определено выполнение ремонтной компании и мероприятий инвестиционной программы 2020 года. </p>
<p>В 2015 году ТОО «КРЭК» был утвержден предельный тариф на 2016-2020 год  в размере 5,18 тенге без НДС с вводом в действие с 1 февраля 2016 года. В связи с чем, изменение утвержденного тарифа возможно в случаях, предусмотренных действующим законодательством. В настоящее время ТОО подана  заявка в Уполномоченный орган на утверждение тарифа и тарифной сметы на период 2021-2025 гг.</p>
