<h1>Отчет о деятельности ТОО "КРЭК" по предоставлению услуг по передаче и (или) распределению электрической энергии в 2017 году перед потребителями и иными заинтересованными лицами</h1>
<p align="center"><b>Отчет</b></p>
<p align="center"><b>о деятельности ТОО "КРЭК" по предоставлению услуг по передаче и (или) распределению электрической энергии в 2017 году перед потребителями и иными заинтересованными лицами</b></p>
<p></p>
<p align="center"><b>Краткая характеристика предприятия</b></p>
<p></p>
<p>Основным видом деятельности ТОО "Карагандинская региональная энергетическая компания" является передача и распределение электрической энергии. Регулируемые услуги оказываются на территории 4-х административных районов Карагандинской области: Абайский, Каркаралинский, Нуринский и Осакаровский. Общая площадь территории обслуживания 98,3 тыс. км<sup>2</sup>, радиус обслуживания электрических сетей составляет 550 км.</p>
<p>Электрические сети и оборудование эксплуатируется с 60-х годов и характеризуются значительной разбросанностью энергообъектов на обслуживаемой территории. Протяженность сетей 6 659,76 км., количество подстанций - 1048 подстанций и КТП, в которых установлено 1 115 трансформаторов. На балансе предприятия имеется спецтехника и транспорт в количестве 104 единиц. Численность персонала на конец года составила 450 человек. К сетям ТОО "КРЭК" подключены порядка 45 154 абонентов, из них физические лица - 43 462, юридические лица - 1 692.</p>
<p></p>
<p align="center"><b>1. Об исполнении инвестиционной программы</b></p>
<p></p>
<p>В рамках утвержденной инвестиционной программы на 2017 год ТОО "КРЭК" были выполнены мероприятия направленные на поддержание в рабочем состоянии основных средств. Сумма утвержденной Инвестиционной программы на 2017 год - 81 800,6 тыс.тенге. В период 2017 года проведен:</p>
<ol>
<li>капитальный ремонт ВЛ 35 кВ "Черниговка-Энтузиаст" 0,59 км;</li>
<li>капитальный ремонт ВЛ 35 кВ "Жумабек-Акбастау" 5,21 км;</li>
<li>капитальный ремонт ВЛ 35 кВ "Осибай-Аркалык" 5,14 км;</li>
<li>капитальный ремонт ВЛ 10 кВ ф.3 с выносом участка от ПС 110/35/10 кВ "Каркаралинск" 0,5 км;</li>
<li>капитальный ремонт ВЛ 0,4 кВ и установку КТП 10/0,4 кВ от ПС 110/35/10 кВ "Каркаралинск" 0,26 км;</li>
</ol>
<p>Кроме того, установлено 303 точки учета АСКУЭ нижнего уровня в г.Каркаралинск.</p>
<p></p>
<p>Мероприятия Инвестиционной программы выполнены в 100% объеме на сумму - 85 841,61 тыс.тенге.</p>
<p></p>
<p align="center"><b>2.Основные финансово-экономические показатели деятельности ТОО "КРЭК" за 2017 год</b></p>
<p></p>
<p align="center"><b><i>Доходы – 1 613 970 736 тенге</i></b></p>
<p>За отчетный период 2017 года доход от оказания регулируемых услуг по передаче и распределению электрической энергии составил 1 565 061 449,7 тенге. При расчете с потребителями за оказанные услуги предприятие применяло предельный тариф в размере 5,18 который был утвержден приказом Департамента Комитета РК по регулированию естественных монополий и защите конкуренции Министерства национальной экономики по Карагандинской области № 264-ОД от 25.12.2015 года.</p>
<p>Доходы от иной деятельности – 48 909 286,36 тенге.</p>
<p></p>
<p align="center"><b><i>Расходы – 1 455 223 446,08 тенге</i></b></p>
<p>Себестоимость реализованной продукции – 1 289 885 648,29 тенге.</p>
<p>Административные расходы – 150 177 413 тенге.</p>
<p>Прочие расходы – 15 160 384,79 тенге.</p>
<p></p>
<p align="center"><b><i>Результат финансово-хозяйственной деятельности</i></b></p>
