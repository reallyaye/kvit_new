<p></p>
<p align="center"><b><i>Краткосрочная дебиторская задолженность - 254 713 тыс. тенге</i></b></p>
<p>ТОО "Жезказган энергосбыт" - 50 328 тыс. тенге</p>
<p>ТОО "Теректы-Энерго" - 42 266 тыс.тенге</p>
