<h1>Отчет о деятельности ТОО "КРЭК" по предоставлению услуг по передаче и (или) распределению электрической энергии в 2018 году перед потребителями и иными заинтересованными лицами</h1>
<p align="center"><b>Отчет</b></p>
<p align="center"><b>о деятельности ТОО "КРЭК" по предоставлению услуг по передаче и (или) распределению электрической энергии в 2018 году перед потребителями и иными заинтересованными лицами</b></p>
<p></p>
<p align="center"><b>Краткая характеристика предприятия</b></p>
<p></p>
<p>Основным видом деятельности ТОО "Карагандинская региональная энергетическая компания" является передача и распределение электрической энергии. Регулируемые услуги оказываются на территории 4-х административных районов Карагандинской области: Абайский, Каркаралинский, Нуринский и Осакаровский. Общая площадь территории обслуживания 98,3 тыс. км<sup>2</sup>, радиус обслуживания электрических сетей составляет 550 км.</p>
<p>Электрические сети и оборудование эксплуатируется с 60-х годов и характеризуются значительной разбросанностью энергообъектов на обслуживаемой территории. Протяженность сетей 6 639,451 км., количество подстанций - 1043 подстанций и КТП, в которых установлено 1 105 трансформаторов. На балансе предприятия имеется спецтехника и транспорт в количестве 104 единиц. Численность персонала на конец года составила 444 человек. К сетям ТОО "КРЭК" подключены порядка 45 157 абонентов, из них физические лица - 43 462, юридические лица - 1 695.</p>
<p></p>
<p align="center"><b>1. Об исполнении инвестиционной программы</b></p>
<p></p>
<p>В рамках утвержденной инвестиционной программы на 2018 год ТОО "КРЭК" были выполнены мероприятия направленные на поддержание в рабочем состоянии основных средств. Сумма утвержденной Инвестиционной программы на 2018 год - 69 272,69 тыс.тенге. В период 2018 года проведен:</p>
<ol>
<li>капитальный ремонт ВЛ 35 кВ "Жумабек-Акбастау" 7,12 км;</li>
<li>капитальный ремонт ВЛ 35 кВ "Донская-17 лет Октября" 1,05 км;</li>
<li>капитальный ремонт ВЛ 10 кВ ф.1 с выносом участка от ПС 110/35/10 кВ "Каркаралинск" 1,7 км;</li>
<li>установка КТП 10/0,4кВ мощьностью 100кВа-1шт.</li>
<li>приобретение КТП в сборе 10 кВа и 40 кВа-2шт.</li>
</ol>
<p>Кроме того, установлено 309 точки учета АСКУЭ нижнего уровня в г.Каркаралинск.</p>
<p></p>
<p>Мероприятия Инвестиционной программы выполнены на сумму - 69 272,69 тыс.тенге.</p>
<p></p>
<p align="center"><b>2.Основные финансово-экономические показатели деятельности ТОО "КРЭК" за 2018 год</b></p>
<p></p>
<p align="center"><b><i>Доходы – 1 589 383 150,68 тенге</i></b></p>
<p>За отчетный период 2018 года  доход от оказания регулируемых услуг по передаче и распределению электрической энергии составил 1 380 857 049,6 тенге. При расчете с потребителями за оказанные услуги до 30.06.2018 года предприятие применяло предельный тариф, утвержденный Уполномоченным органом в размере 5,18 тенге кВтч, с 01.07.2018 был введен компенсирующий тариф в размере 4,90 тенге/кВтч, далее, 01.12.2018 года был введен компенсирующий тариф в размере 4,08 тенге/кВтч.</p>
<p>Доходы от иной деятельности – 33 901 119,1 тенге.</p>
<p></p>
<p align="center"><b><i>Расходы – 1 580 107 746 тенге</i></b></p>
<p>Себестоимость реализованной продукции – 1 351 313 230,73  тенге.</p>
<p>Административные расходы – 228 794 515,27  тенге.</p>
<p>Прочие расходы – 1 888 722,86 тенге.</p>
<p></p>
<p align="center"><b><i>Результат финансово-хозяйственной деятельности</i></b></p>
<p>Прибыль до налогообложения составил 7 387 тенге.</p>
<p></p>
<p align="center"><b><i>Краткосрочная дебиторская задолженность - 179 216 тыс. тенге</i></b></p>
<p>ТОО "Жезказган энергосбыт" - 53 291 тыс. тенге</p>
<p>ТОО "Теректы-Энерго" - 17 293 тыс.тенге</p>
